package operator

import (
	"context"
	"fmt"
	"strings"

	corev1 "k8s.io/api/core/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/controller-runtime/pkg/client"

	"github.com/clear-route/orbit/internal/platform/logging"
)

const (
	// tenantsConfigMapName is the ConfigMap read by the identity service to
	// discover tenant OIDC providers. See ADR-0023.
	tenantsConfigMapName = "orbit-tenants"

	// tenantsConfigMapKey is the key within the ConfigMap that holds the YAML.
	tenantsConfigMapKey = "tenants.yaml"

	// systemNamespace is the namespace where the tenants ConfigMap lives.
	systemNamespace = "orbit-system"
)

// TenantRegistry manages the orbit-tenants ConfigMap. It translates the set of
// active OrbitTenant CRs into the ADR-0023 tenant registry YAML format that
// the identity service reads at startup and on SIGHUP.
//
// Registry operations are idempotent — calling Sync multiple times with the
// same tenant list is safe.
type TenantRegistry struct {
	client client.Client
	logger logging.Logger
}

// NewTenantRegistry creates a TenantRegistry backed by the provided client.
func NewTenantRegistry(c client.Client, logger logging.Logger) *TenantRegistry {
	return &TenantRegistry{client: c, logger: logger}
}

// Sync rebuilds the orbit-tenants ConfigMap from the current list of
// OrbitTenant CRs. It creates the ConfigMap if absent and patches it if
// the content has changed.
func (r *TenantRegistry) Sync(ctx context.Context) error {
	tenants, err := r.listActiveTenants(ctx)
	if err != nil {
		return fmt.Errorf("list tenants: %w", err)
	}

	yaml := r.buildRegistryYAML(tenants)

	existing := &corev1.ConfigMap{}
	err = r.client.Get(ctx, client.ObjectKey{
		Namespace: systemNamespace,
		Name:      tenantsConfigMapName,
	}, existing)

	switch {
	case apierrors.IsNotFound(err):
		return r.createConfigMap(ctx, yaml)
	case err != nil:
		return fmt.Errorf("get %s ConfigMap: %w", tenantsConfigMapName, err)
	default:
		if existing.Data[tenantsConfigMapKey] == yaml {
			r.logger.Debug(ctx, "tenant registry unchanged, skipping update")
			return nil
		}
		return r.updateConfigMap(ctx, existing, yaml)
	}
}

// -----------------------------------------------------------------------------
// private helpers
// -----------------------------------------------------------------------------

func (r *TenantRegistry) listActiveTenants(ctx context.Context) ([]OrbitTenant, error) {
	list := &OrbitTenantList{}
	if err := r.client.List(ctx, list); err != nil {
		return nil, fmt.Errorf("list OrbitTenants: %w", err)
	}

	active := make([]OrbitTenant, 0, len(list.Items))
	for _, t := range list.Items {
		if t.Spec.Active {
			active = append(active, t)
		}
	}
	return active, nil
}

// buildRegistryYAML produces the ADR-0023 tenant registry YAML that the
// identity service parses. The format must remain stable — the identity
// service owns the schema; the operator only writes it.
//
// Example output:
//
//	version: "v1"
//	tenants:
//	  - id: "acme"
//	    displayName: "Acme Corp"
//	    state: "active"
//	    oidc:
//	      issuerURL: "https://accounts.google.com"
//	      clientID: "123.apps.googleusercontent.com"
//	      clientSecretEnv: "ORBIT_TENANT_ACME_OIDC_CLIENT_SECRET"
//	      scopes: [openid, profile, email]
func (r *TenantRegistry) buildRegistryYAML(tenants []OrbitTenant) string {
	var b strings.Builder

	b.WriteString("# Generated by orbit-operator — do not edit manually.\n")
	b.WriteString("# See ADR-0023 for the tenant registry schema.\n")
	b.WriteString("version: \"v1\"\n")
	b.WriteString("\n")
	b.WriteString("tenants:\n")

	for _, t := range tenants {
		state := "active"
		if !t.Spec.Active {
			state = "suspended"
		}

		fmt.Fprintf(&b, "  - id: %q\n", t.Name)
		fmt.Fprintf(&b, "    displayName: %q\n", t.Spec.DisplayName)
		fmt.Fprintf(&b, "    state: %q\n", state)
		b.WriteString("    oidc:\n")
		fmt.Fprintf(&b, "      issuerURL: %q\n", t.Spec.OIDC.IssuerURL)
		fmt.Fprintf(&b, "      clientID: %q\n", t.Spec.OIDC.ClientID)

		// Build the env var name from the tenant ID following the project
		// convention: ORBIT_TENANT_{UPPER_ID}_OIDC_CLIENT_SECRET.
		// The operator never reads the secret value — it only writes the
		// env var name. The secret itself is injected into the identity pod
		// via envFrom on the orbit-secrets Secret.
		envVar := tenantOIDCSecretEnvVar(t.Name)
		fmt.Fprintf(&b, "      clientSecretEnv: %q\n", envVar)

		scopes := t.Spec.OIDC.Scopes
		if len(scopes) == 0 {
			scopes = []string{"openid", "profile", "email"}
		}
		fmt.Fprintf(&b, "      scopes: [%s]\n", strings.Join(scopes, ", "))
	}

	return b.String()
}

// tenantOIDCSecretEnvVar derives the env var name that the identity service
// reads to obtain the OIDC client secret for a given tenant.
//
// Convention: ORBIT_TENANT_{UPPER_SANITIZED_ID}_OIDC_CLIENT_SECRET
// e.g. tenant id "acme-corp" → ORBIT_TENANT_ACME_CORP_OIDC_CLIENT_SECRET
func tenantOIDCSecretEnvVar(tenantID string) string {
	upper := strings.ToUpper(tenantID)
	sanitized := strings.Map(func(r rune) rune {
		if (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
			return r
		}
		return '_'
	}, upper)
	return fmt.Sprintf("ORBIT_TENANT_%s_OIDC_CLIENT_SECRET", sanitized)
}

func (r *TenantRegistry) createConfigMap(ctx context.Context, yaml string) error {
	cm := &corev1.ConfigMap{
		ObjectMeta: metav1.ObjectMeta{
			Name:      tenantsConfigMapName,
			Namespace: systemNamespace,
			Labels: map[string]string{
				"app.kubernetes.io/managed-by": "orbit-operator",
				"orbit.io/component":           "tenant-registry",
			},
		},
		Data: map[string]string{
			tenantsConfigMapKey: yaml,
		},
	}
	if err := r.client.Create(ctx, cm); err != nil {
		return fmt.Errorf("create %s ConfigMap: %w", tenantsConfigMapName, err)
	}
	r.logger.Info(ctx, "created tenant registry ConfigMap",
		logging.Field{Key: "configmap", Value: tenantsConfigMapName},
		logging.Field{Key: "namespace", Value: systemNamespace},
	)
	return nil
}

func (r *TenantRegistry) updateConfigMap(ctx context.Context, existing *corev1.ConfigMap, yaml string) error {
	patch := client.MergeFrom(existing.DeepCopy())
	if existing.Data == nil {
		existing.Data = make(map[string]string)
	}
	existing.Data[tenantsConfigMapKey] = yaml

	if err := r.client.Patch(ctx, existing, patch); err != nil {
		return fmt.Errorf("patch %s ConfigMap: %w", tenantsConfigMapName, err)
	}
	r.logger.Info(ctx, "updated tenant registry ConfigMap",
		logging.Field{Key: "configmap", Value: tenantsConfigMapName},
		logging.Field{Key: "namespace", Value: systemNamespace},
	)
	return nil
}
