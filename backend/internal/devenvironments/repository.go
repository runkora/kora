package devenvironments

import (
	"context"
	"time"
)

// Record is the Postgres registry row for one environment: ownership and
// audit trail. Lifecycle state (phase, ingress host, expiry, ...) is never
// duplicated here — it is read live from the OrbitDevEnvironment CR via
// CRClient, so the registry can never drift out of sync with the operator's
// own view of an environment.
type Record struct {
	ID        string
	Owner     string
	Ref       string
	CreatedAt time.Time
	DeletedAt *time.Time
}

// Repository is the storage contract for the devenvironments registry.
type Repository interface {
	// Create inserts a new registry row. id is the environment ID (also the
	// CR name) generated by the service layer.
	Create(ctx context.Context, rec *Record) error
	// Get returns a row regardless of owner — callers enforce ownership.
	Get(ctx context.Context, id string) (*Record, error)
	// ListByOwner returns every non-deleted row owned by owner, newest first.
	ListByOwner(ctx context.Context, owner string) ([]Record, error)
	// ListAll returns every non-deleted row regardless of owner (admin listing).
	ListAll(ctx context.Context) ([]Record, error)
	// MarkDeleted soft-deletes a row (audit trail retained) once its CR has
	// been deleted, whether by explicit destroy or TTL expiry.
	MarkDeleted(ctx context.Context, id string) error
	// CountActiveByOwner counts owner's non-deleted rows, for quota enforcement.
	CountActiveByOwner(ctx context.Context, owner string) (int, error)
}
