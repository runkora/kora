package triggers

import (
	"crypto/hmac"
	"crypto/sha256"
	_ "embed"
	"encoding/hex"
	"net/http"
	"strings"
)

type githubAdapter struct{}

func (a *githubAdapter) Provider() string { return ProviderGitHub }

// Verify implements GitHub's HMAC-SHA256 scheme: the X-Hub-Signature-256 header
// carries "sha256=<hex>" over the raw request body keyed by the signing secret.
// Comparison is constant-time.
func (a *githubAdapter) Verify(secret string, headers http.Header, body []byte) error {
	sig := headers.Get("X-Hub-Signature-256")
	const prefix = "sha256="
	if !strings.HasPrefix(sig, prefix) {
		return ErrSignatureInvalid
	}
	want, err := hex.DecodeString(strings.TrimPrefix(sig, prefix))
	if err != nil {
		return ErrSignatureInvalid
	}
	mac := hmac.New(sha256.New, []byte(secret))
	mac.Write(body)
	if !hmac.Equal(want, mac.Sum(nil)) {
		return ErrSignatureInvalid
	}
	return nil
}

// DeliveryID returns GitHub's per-delivery id. Replay protection relies entirely
// on this id (deduped via the partial unique index on trigger_deliveries) — the
// adapter does not inspect any timestamp header, so there is no time-window
// replay defense. A delivery with no id is rejected fail-closed in Service.Ingest
// rather than accepted unprotected. If a provider/requirement ever needs
// timestamp-based anti-replay, it belongs here alongside the id.
func (a *githubAdapter) DeliveryID(headers http.Header, _ []byte) string {
	return headers.Get("X-GitHub-Delivery")
}

func (a *githubAdapter) EventType(headers http.Header, _ []byte) string {
	return headers.Get("X-GitHub-Event")
}

//go:embed schemas/github.json
var githubSchema []byte

// Schema returns GitHub's webhook schemas, generated by tools/trigger-schemas.
func (a *githubAdapter) Schema() []byte { return githubSchema }

// associationObjects are the payload objects that carry author_association, in
// the order the sender's association is looked up.
var associationObjects = []string{"comment", "review", "answer", "discussion", "issue", "pull_request"}

// Sender reads sender.login. The association is the author_association of the
// first object the sender authored; GitHub reports it for authors only.
func (a *githubAdapter) Sender(_ string, body any) (Sender, bool) {
	login := resolvePath(body, "sender.login")
	if login == "" {
		return Sender{}, false
	}
	s := Sender{Login: a.NormalizeLogin(login)}
	for _, obj := range associationObjects {
		author := resolvePath(body, obj+".user.login")
		if author != "" && a.NormalizeLogin(author) == s.Login {
			s.Association = resolvePath(body, obj+".author_association")
			break
		}
	}
	return s, true
}

// NormalizeLogin lowercases a login; GitHub logins are case-insensitive.
func (a *githubAdapter) NormalizeLogin(login string) string { return strings.ToLower(login) }

// Associations are the repository relationships a restriction may name.
func (a *githubAdapter) Associations() []string {
	return []string{"OWNER", "MEMBER", "COLLABORATOR"}
}
