// Command gen builds the GitHub REST route table the github_app connector
// classifies by. See docs/adr/2026-11-15-github-connector-route-coverage.md.
//
// Run from backend/:
//
//	go run ./internal/credentials/adapters/githubapp/gen -fetch  # refresh the trimmed data from github/docs
//	go run ./internal/credentials/adapters/githubapp/gen         # regenerate routes_gen.go from it
//
// The trimmed data is committed so make generate-check runs offline. To pick
// up new endpoints, move docsCommit and run with -fetch.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"slices"
	"strings"
	"time"
)

// docsCommit is the github/docs commit the route table is generated from.
const docsCommit = "d59b2631959db46d71ca5f7748ec04311c6d0870"

const (
	dataFile   = "internal/credentials/adapters/githubapp/testdata/github-rest-permissions.json"
	outputFile = "internal/credentials/adapters/githubapp/routes_gen.go"

	restDataDir     = "src/rest/data/fpt-2022-11-28"
	permissionsFile = "src/github-apps/data/fpt-2022-11-28/server-to-server-permissions.json"
)

// route is one endpoint an installation token can call. Sets are GitHub's
// alternative permission sets: any one set, held in full, authorizes the call.
type route struct {
	Method string              `json:"method"`
	Path   string              `json:"path"`
	Sets   []map[string]string `json:"sets"`
}

type data struct {
	Commit string  `json:"commit"`
	Routes []route `json:"routes"`
}

func main() {
	fetch := flag.Bool("fetch", false, "download the route data from github/docs at docsCommit")
	flag.Parse()
	if err := run(*fetch); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(fetch bool) error {
	if fetch {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
		defer cancel()
		d, err := download(ctx)
		if err != nil {
			return err
		}
		buf, err := json.MarshalIndent(d, "", " ")
		if err != nil {
			return fmt.Errorf("encode data: %w", err)
		}
		if err := os.WriteFile(dataFile, append(buf, '\n'), 0o600); err != nil {
			return fmt.Errorf("write data: %w", err)
		}
	}
	buf, err := os.ReadFile(dataFile)
	if err != nil {
		return fmt.Errorf("read data: %w", err)
	}
	var d data
	if err = json.Unmarshal(buf, &d); err != nil {
		return fmt.Errorf("decode data: %w", err)
	}
	src, err := render(d)
	if err != nil {
		return err
	}
	if err := os.WriteFile(outputFile, src, 0o600); err != nil {
		return fmt.Errorf("write table: %w", err)
	}
	return nil
}

// render writes the table as Go source.
func render(d data) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by ./gen; DO NOT EDIT.\n// Source: github/docs %s, %s.\n\npackage githubapp\n\n", d.Commit, restDataDir)
	b.WriteString("var restRoutes = []restRoute{\n")
	for _, r := range d.Routes {
		fmt.Fprintf(&b, "\t{%q, %q, []permissionSet{", r.Method, r.Path)
		for _, set := range r.Sets {
			b.WriteString("{")
			for _, key := range sortedKeys(set) {
				fmt.Fprintf(&b, "%q: %q, ", key, set[key])
			}
			b.WriteString("}, ")
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format table: %w", err)
	}
	return src, nil
}

// download reads every REST operation's server-to-server permission sets from
// github/docs, with GitHub's display names turned into token permission keys.
func download(ctx context.Context) (data, error) {
	keys, err := permissionKeys(ctx)
	if err != nil {
		return data{}, err
	}
	var listing []struct {
		Name string `json:"name"`
	}
	if err := getJSON(ctx, "https://api.github.com/repos/github/docs/contents/"+restDataDir+"?ref="+docsCommit, &listing); err != nil {
		return data{}, err
	}
	seen := map[string]route{}
	for _, f := range listing {
		if !strings.HasSuffix(f.Name, ".json") {
			continue
		}
		var doc any
		if err := getJSON(ctx, rawURL(restDataDir+"/"+f.Name), &doc); err != nil {
			return data{}, err
		}
		collect(doc, keys, seen)
	}
	routes := make([]route, 0, len(seen))
	for _, r := range seen {
		routes = append(routes, r)
	}
	slices.SortFunc(routes, func(a, b route) int {
		return strings.Compare(a.Path+" "+a.Method, b.Path+" "+b.Method)
	})
	return data{Commit: docsCommit, Routes: routes}, nil
}

// permissionKeys maps the display names in progAccess (`"Issues" repository
// permissions`) to token permission keys (issues).
func permissionKeys(ctx context.Context) (map[string]string, error) {
	var perms map[string]struct {
		DisplayTitle string `json:"displayTitle"`
	}
	if err := getJSON(ctx, rawURL(permissionsFile), &perms); err != nil {
		return nil, err
	}
	keys := map[string]string{}
	for key, p := range perms {
		kind, title, ok := strings.Cut(p.DisplayTitle, " permissions for ")
		if !ok {
			return nil, fmt.Errorf("unexpected display title %q", p.DisplayTitle)
		}
		keys[title+" "+strings.ToLower(kind)+" permissions"] = key
	}
	return keys, nil
}

// collect walks a REST data document for operations installation tokens can call.
func collect(node any, keys map[string]string, seen map[string]route) {
	switch n := node.(type) {
	case []any:
		for _, v := range n {
			collect(v, keys, seen)
		}
	case map[string]any:
		if path, ok := n["requestPath"].(string); ok {
			addOperation(n, path, keys, seen)
			return
		}
		for _, v := range n {
			collect(v, keys, seen)
		}
	}
}

func addOperation(op map[string]any, path string, keys map[string]string, seen map[string]route) {
	access, _ := op["progAccess"].(map[string]any)
	if s2s, _ := access["serverToServer"].(bool); !s2s {
		return
	}
	verb, _ := op["verb"].(string)
	r := route{Method: strings.ToUpper(verb), Path: path, Sets: []map[string]string{}}
	sets, _ := access["permissions"].([]any)
	for _, s := range sets {
		raw, _ := s.(map[string]any)
		set := map[string]string{}
		for name, level := range raw {
			// A permission outside the installation token's set keeps its display
			// name, which no category maps to.
			key, ok := keys[name]
			if !ok {
				key = name
			}
			set[key], _ = level.(string)
		}
		r.Sets = append(r.Sets, set)
	}
	seen[r.Method+" "+r.Path] = r
}

func rawURL(path string) string {
	return "https://raw.githubusercontent.com/github/docs/" + docsCommit + "/" + path
}

func getJSON(ctx context.Context, url string, v any) error {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, http.NoBody)
	if err != nil {
		return fmt.Errorf("build request: %w", err)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return fmt.Errorf("get %s: %w", url, err)
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("get %s: status %d", url, resp.StatusCode)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return fmt.Errorf("read %s: %w", url, err)
	}
	if err := json.Unmarshal(body, v); err != nil {
		return fmt.Errorf("decode %s: %w", url, err)
	}
	return nil
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
