// Command gen-ts writes the TypeScript harness list from the Go list.
//
//	go run ./internal/platform/harnesses/cmd/gen-ts <output file>
package main

import (
	"fmt"
	"os"
	"strconv"
	"strings"

	"github.com/runkora/kora/backend/internal/platform/harnesses"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen-ts <output file>")
		os.Exit(2)
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/platform/harnesses/cmd/gen-ts. DO NOT EDIT.\n")
	b.WriteString("// Edit backend/internal/platform/harnesses/harnesses.go and run `make generate`.\n\n")
	b.WriteString("export const AGENT_FRAMEWORKS = [\n")
	for _, h := range harnesses.All() {
		fmt.Fprintf(&b, "  { id: %s, label: %s, description: %s },\n",
			strconv.Quote(h.ID), strconv.Quote(h.Label), strconv.Quote(h.Description))
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type AgentFramework = (typeof AGENT_FRAMEWORKS)[number]['id'];\n\n")
	b.WriteString("export const FRAMEWORK_LABELS: Record<string, string> = {\n")
	for _, h := range harnesses.All() {
		fmt.Fprintf(&b, "  %s: %s,\n", strconv.Quote(h.ID), strconv.Quote(h.Label))
	}
	b.WriteString("};\n")
	if err := os.WriteFile(os.Args[1], []byte(b.String()), 0o600); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
